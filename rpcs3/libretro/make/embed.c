/* The Makefile's stand-in for the CMake build's embed_*.cmake scripts: files
 * compiled into the core as byte arrays, written out as C++ the same way.
 * Built for the machine that runs the build (HOST_CC), as C99, with
 * libretro-common's JSON reader and SHA-256.
 *
 *   embed bytes OUT ARRAY SIZE_NAME COMMENT FILE
 *       FILE as `extern const unsigned char ARRAY[]` (with a 0 after it)
 *       and `extern const std::size_t SIZE_NAME`; an absent FILE as empty
 *   embed icons OUT DIR NAME...
 *       the overlays' icons, DIR/NAME each, as libretro_ui_icons.h's table
 *   embed patch OUT VERSION JSON YML
 *       patch.yml for the patch engine VERSION: from rpcs3.net's answer
 *       JSON when it is a good one (its sha256 checked), else YML, the
 *       mirror's file, when it is for VERSION, else nothing; as the bytes
 *       of g_libretro_patch_yml
 *
 * Each OUT is written only when it changes, so make rebuilds nothing when
 * the data is the same. */

#include <stdio.h>
#include <stdlib.h>
#include <string.h>

#include <formats/rjson.h>
#include <lrc_hash.h>

static char *slurp(const char *path, size_t *len)
{
   char *buf;
   long  n;
   FILE *f = fopen(path, "rb");
   *len    = 0;
   if (!f)
      return NULL;
   fseek(f, 0, SEEK_END);
   n = ftell(f);
   fseek(f, 0, SEEK_SET);
   buf = (char*)malloc((size_t)(n > 0 ? n : 0) + 1);
   if (n > 0 && fread(buf, 1, (size_t)n, f) != (size_t)n)
      n = 0;
   fclose(f);
   *len      = (size_t)(n > 0 ? n : 0);
   buf[*len] = 0;
   return buf;
}

/* The output, collected, then written only when it differs */
struct out
{
   char  *p;
   size_t len, cap;
};

static void put(struct out *o, const char *s, size_t n)
{
   if (o->len + n > o->cap)
   {
      o->cap = (o->len + n) * 2 + 4096;
      o->p   = (char*)realloc(o->p, o->cap);
   }
   memcpy(o->p + o->len, s, n);
   o->len += n;
}

static void puts_(struct out *o, const char *s)
{
   put(o, s, strlen(s));
}

static void put_bytes(struct out *o, const unsigned char *b, size_t n)
{
   static const char hex[] = "0123456789abcdef";
   char   cell[6]          = { '0', 'x', 0, 0, ',', 0 };
   size_t i;
   for (i = 0; i < n; i++)
   {
      cell[2] = hex[b[i] >> 4];
      cell[3] = hex[b[i] & 15];
      put(o, cell, 5);
      if ((i & 31) == 31)
         put(o, "\n", 1);
   }
}

static int finish(struct out *o, const char *path)
{
   size_t old_len;
   char  *old = slurp(path, &old_len);
   int    same = old && old_len == o->len && !memcmp(old, o->p, o->len);
   free(old);
   if (!same)
   {
      FILE *f = fopen(path, "wb");
      if (!f || fwrite(o->p, 1, o->len, f) != o->len)
      {
         fprintf(stderr, "embed: cannot write %s\n", path);
         if (f)
            fclose(f);
         return 1;
      }
      fclose(f);
   }
   free(o->p);
   return 0;
}

static int write_bytes(const char *out_path, const char *array, const char *size_name,
      const char *comment, const unsigned char *data, size_t len)
{
   struct out o = { NULL, 0, 0 };
   char       num[32];
   puts_(&o, "// Generated by ");
   puts_(&o, comment);
   puts_(&o, "\n#include <cstddef>\n\nextern const unsigned char ");
   puts_(&o, array);
   puts_(&o, "[] = {\n");
   put_bytes(&o, data, len);
   puts_(&o, "0};\nextern const std::size_t ");
   puts_(&o, size_name);
   sprintf(num, " = %lu;\n", (unsigned long)len);
   puts_(&o, num);
   return finish(&o, out_path);
}

static int do_icons(const char *out_path, const char *dir, int count, char **names)
{
   struct out o = { NULL, 0, 0 };
   struct out t = { NULL, 0, 0 };
   char       line[512];
   int        i;
   puts_(&o, "// Generated by rpcs3/libretro/make/embed.c from bin/Icons/ui\n#include \"libretro_ui_icons.h\"\n\n");
   for (i = 0; i < count; i++)
   {
      size_t len;
      char   path[1024];
      unsigned char *data;
      snprintf(path, sizeof(path), "%s/%s", dir, names[i]);
      data = (unsigned char*)slurp(path, &len);
      if (!data)
      {
         fprintf(stderr, "embed: cannot read %s\n", path);
         return 1;
      }
      sprintf(line, "static const unsigned char icon_%d[] = {", i);
      puts_(&o, line);
      put_bytes(&o, data, len);
      puts_(&o, "};\n");
      snprintf(line, sizeof(line), "    {\"%s\", icon_%d, %lu},\n", names[i], i, (unsigned long)len);
      puts_(&t, line);
      free(data);
   }
   puts_(&o, "\nconst libretro_ui_icon g_libretro_ui_icons[] = {\n");
   put(&o, t.p ? t.p : "", t.len);
   sprintf(line, "};\nconst std::size_t g_libretro_ui_icon_count = %d;\n", count);
   puts_(&o, line);
   free(t.p);
   return finish(&o, out_path);
}

/* rpcs3.net's answer: {"return_code":0,"patch":"...","sha256":"..."} */
struct patch_answer
{
   char  *patch;
   size_t patch_len;
   char   sha256[65];
   int    code, have_code;
};

static char *patch_from_json(const char *json, size_t len, size_t *out_len)
{
   struct patch_answer a;
   rjson_t            *j = rjson_open_buffer(json, len);
   char                digest[65];
   enum rjson_type     t;
   memset(&a, 0, sizeof(a));
   if (!j)
      return NULL;
   if (rjson_next(j) != RJSON_OBJECT)
   {
      rjson_free(j);
      return NULL;
   }
   while ((t = rjson_next(j)) == RJSON_STRING)
   {
      size_t      klen;
      const char *key = rjson_get_string(j, &klen);
      char        name[16];
      if (klen >= sizeof(name))
         klen = sizeof(name) - 1;
      memcpy(name, key, klen);
      name[klen] = 0;
      t = rjson_next(j);
      if (!strcmp(name, "return_code") && t == RJSON_NUMBER)
      {
         a.code      = rjson_get_int(j);
         a.have_code = 1;
      }
      else if (!strcmp(name, "patch") && t == RJSON_STRING)
      {
         size_t      n;
         const char *s = rjson_get_string(j, &n);
         a.patch       = (char*)malloc(n + 1);
         memcpy(a.patch, s, n);
         a.patch[n]  = 0;
         a.patch_len = n;
      }
      else if (!strcmp(name, "sha256") && t == RJSON_STRING)
      {
         size_t      n;
         const char *s = rjson_get_string(j, &n);
         if (n == 64)
            memcpy(a.sha256, s, 64);
      }
      else if (t == RJSON_OBJECT || t == RJSON_ARRAY)
      {
         /* skip what is inside */
         unsigned depth = 1;
         while (depth && (t = rjson_next(j)) != RJSON_DONE && t != RJSON_ERROR)
         {
            if (t == RJSON_OBJECT || t == RJSON_ARRAY)
               depth++;
            else if (t == RJSON_OBJECT_END || t == RJSON_ARRAY_END)
               depth--;
         }
      }
   }
   rjson_free(j);
   if (!a.patch || !a.have_code || a.code != 0 || !a.sha256[0])
   {
      free(a.patch);
      return NULL;
   }
   sha256_hash(digest, (const uint8_t*)a.patch, a.patch_len);
   {
      /* lowercase hex against either case */
      int i;
      for (i = 0; i < 64; i++)
         if (a.sha256[i] >= 'A' && a.sha256[i] <= 'F')
            a.sha256[i] = (char)(a.sha256[i] - 'A' + 'a');
   }
   if (strncmp(digest, a.sha256, 64))
   {
      fprintf(stderr, "embed: patch.yml from rpcs3.net does not match its sha256\n");
      free(a.patch);
      return NULL;
   }
   *out_len = a.patch_len;
   return a.patch;
}

static int do_patch(const char *out_path, const char *version, const char *json_path, const char *yml_path)
{
   size_t len = 0, patch_len = 0;
   char  *json = slurp(json_path, &len);
   char  *patch = json && len ? patch_from_json(json, len, &patch_len) : NULL;
   char   prefix[64];
   int    r;
   free(json);
   if (!patch)
   {
      patch = slurp(yml_path, &patch_len);
      snprintf(prefix, sizeof(prefix), "Version: %s", version);
      if (patch && strncmp(patch, prefix, strlen(prefix)))
      {
         free(patch);
         patch     = NULL;
         patch_len = 0;
      }
   }
   if (patch)
      printf("embed: patch.yml for patch engine %s embedded\n", version);
   else
      fprintf(stderr, "embed: patch.yml not downloaded; the core is built without it\n");
   r = write_bytes(out_path, "g_libretro_patch_yml", "g_libretro_patch_yml_size",
         "rpcs3/libretro/make/embed.c from rpcs3.net's patch.yml",
         (const unsigned char*)(patch ? patch : ""), patch_len);
   free(patch);
   return r;
}

int main(int argc, char **argv)
{
   if (argc == 7 && !strcmp(argv[1], "bytes"))
   {
      size_t len;
      char  *data = slurp(argv[6], &len);
      char   comment[512];
      int    r;
      snprintf(comment, sizeof(comment), "rpcs3/libretro/make/embed.c from %s", argv[5]);
      r = write_bytes(argv[2], argv[3], argv[4], comment, (const unsigned char*)(data ? data : ""), len);
      free(data);
      return r;
   }
   if (argc >= 4 && !strcmp(argv[1], "icons"))
      return do_icons(argv[2], argv[3], argc - 4, argv + 4);
   if (argc == 6 && !strcmp(argv[1], "patch"))
      return do_patch(argv[2], argv[3], argv[4], argv[5]);
   fprintf(stderr, "usage: embed bytes OUT ARRAY SIZE_NAME COMMENT FILE | icons OUT DIR NAME... | patch OUT VERSION JSON YML\n");
   return 2;
}
